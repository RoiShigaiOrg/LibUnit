#include "libft.h"

void	ft_lstiter(t_list *lst, void (*f)(void *))
{
	t_list	*ptr;

	ptr = lst;
	if (f == NULL)
		return ;
	while (ptr != NULL)
	{
		(*f)(ptr->content);
		if (ptr->next == lst)
			return ;
		ptr = ptr->next;
	}
}
