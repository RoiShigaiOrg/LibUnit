#include "libft.h"

int	ft_lstsize(t_list *lst)
{
	int			i;
	t_list		tmp;

	if (lst == NULL)
		return (0);
	tmp = *lst;
	i = 1;
	while (tmp.next != NULL && tmp.next != lst)
	{
		tmp = *tmp.next;
		i++;
	}
	return (i);
}
